def bcc(data):
    c = 0xFF
    for b in data:
        c = CCITT8[c ^ b]
    return c


def check(name, frame_hex, expect):
    data = bytes.fromhex(frame_hex.replace(" ", ""))
    got = bcc(data)
    status = "OK " if got == expect else "FAIL"
    print(f"{status} {name}: expected {expect:#04x} got {got:#04x}")
    return got == expect



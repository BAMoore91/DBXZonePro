# Now validate the frame BUILDER (mirrors the JS driver logic) against the same vectors.
def build_multisvset(node, obj, sv_id, dtype, value, flags=0x0000):
    if dtype == 1:
        val = [value & 0xFF]
    elif dtype == 3:
        val = [(value >> 8) & 0xFF, value & 0xFF]
    else:
        raise ValueError("unsupported dtype")
    payload = [0x00, 0x01, (sv_id >> 8) & 0xFF, sv_id & 0xFF, dtype] + val
    length = 21 + len(payload)
    msg = ([0x01] +
           [(length >> 24) & 0xFF, (length >> 16) & 0xFF, (length >> 8) & 0xFF, length & 0xFF] +
           [0x00, 0x33] + list(obj) +
           list(node) + list(obj) +
           [0x01, 0x00] +
           [(flags >> 8) & 0xFF, flags & 0xFF] +
           payload)
    return msg


def frame_serial(msg):
    body = [0x64, 0x00] + msg
    return [0xF0] + body + [bcc(bytes(body))]


def hexs(b):
    return " ".join(f"{x:02X}" for x in b)



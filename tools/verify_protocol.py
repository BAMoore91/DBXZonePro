# Recall Scene builder: header only + UWORD scene, LEN must be 0x17 (23)
def build_recall_scene(node, scene):
    payload = [(scene >> 8) & 0xFF, scene & 0xFF]
    length = 21 + len(payload)
    assert length == 0x17
    return ([0x01, 0x00, 0x00, 0x00, length,
             0x00, 0x33, 0x00, 0x00, 0x00, 0x00] +
            list(node) + [0x00, 0x00, 0x00, 0x00] +
            [0x90, 0x01, 0x00, 0x00] + payload)


